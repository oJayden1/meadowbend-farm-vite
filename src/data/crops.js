export const CROP_KEYS = Object.keys(CROPS);

export function getItemMeta(kind, id) {
  if (kind === 'seed' && CROPS[id]) {
    return {
      kind: 'seed',
      id,
      name: `${CROPS[id].name} Seeds`,
      shortLabel: CROPS[id].name.split(' ').pop(),
      icon: CROPS[id].icon,
      category: 'Seed'
    };
  }
  if (kind === 'crop' && CROPS[id]) {
    return {
      kind: 'crop',
      id,
      name: CROPS[id].name,
      shortLabel: CROPS[id].name.split(' ').pop(),
      icon: CROPS[id].harvestIcon,
      category: 'Harvested Crop'
    };
  }
  if (kind === 'placeable' && id === 'fence') {
    return {
      kind: 'placeable',
      id: 'fence',
      name: 'Wooden Fence',
      shortLabel: 'Fence',
      icon: '🪵',
      category: 'Structure'
    };
  }
  if (kind === 'placeable' && id === 'gate') {
    return {
      kind: 'placeable',
      id: 'gate',
      name: 'Fence Gate',
      shortLabel: 'Gate',
      icon: '🚪',
      category: 'Structure'
    };
  }
  return null;
}
